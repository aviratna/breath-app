import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { doc, getDoc, setDoc, updateDoc, deleteDoc, addDoc, collection, getDocs, query, orderBy, limit, serverTimestamp, writeBatch } from 'firebase/firestore';
import fs from 'fs';
import { setLogLevel } from 'firebase/firestore';
setLogLevel('silent');
const env = await initializeTestEnvironment({ projectId: 'demo-breath', firestore: { rules: fs.readFileSync(new URL('./firestore.rules', import.meta.url), 'utf8'), host: '127.0.0.1', port: 8089 } });
const A = env.authenticatedContext('alice').firestore();
const B = env.authenticatedContext('bob').firestore();
const M = env.authenticatedContext('mallory').firestore();
const U = env.unauthenticatedContext().firestore();
let n = 0, fail = 0;
const ok = async (label, p) => { n++; try { await assertSucceeds(p); console.log('  ✓ allow', label); } catch (e) { fail++; console.log('  ✗ SHOULD ALLOW', label, e.message); } };
const no = async (label, p) => { n++; try { await assertFails(p); console.log('  ✓ deny ', label); } catch (e) { fail++; console.log('  ✗ SHOULD DENY', label); } };
const conn = (db, owner, other, name) => doc(db, 'users', owner, 'connections', other);
const ts = () => serverTimestamp();

console.log('profiles & codes');
await ok('alice creates code', setDoc(doc(A, 'codes', 'AAAAA2'), { uid: 'alice', name: 'Alice' }));
await ok('bob creates code', setDoc(doc(B, 'codes', 'BBBBB2'), { uid: 'bob', name: 'Bob' }));
await no('mallory steals existing code', setDoc(doc(M, 'codes', 'AAAAA2'), { uid: 'mallory', name: 'M' }));
await no('code for someone else', setDoc(doc(M, 'codes', 'MMMMM2'), { uid: 'alice', name: 'M' }));
await no('bad code format', setDoc(doc(M, 'codes', 'abc'), { uid: 'mallory', name: 'M' }));
await no('list all codes', getDocs(collection(M, 'codes')));
await no('signed-out read code', getDoc(doc(U, 'codes', 'AAAAA2')));
await ok('look up a code', getDoc(doc(B, 'codes', 'AAAAA2')));
await ok('alice profile', setDoc(doc(A, 'users', 'alice'), { name: 'Alice', code: 'AAAAA2', createdAt: ts() }));
await ok('bob profile', setDoc(doc(B, 'users', 'bob'), { name: 'Bob', code: 'BBBBB2', createdAt: ts() }));
await no('read someone else profile', getDoc(doc(M, 'users', 'alice')));
await no('name too long', setDoc(doc(M, 'users', 'mallory'), { name: 'x'.repeat(41), code: 'X', createdAt: ts() }));

console.log('connecting (bob enters alice code)');
const bb = writeBatch(B);
bb.set(conn(B, 'bob', 'alice'), { name: 'Alice', blocked: false, since: ts() });
bb.set(conn(B, 'alice', 'bob'), { name: 'Bob', blocked: false, since: ts() });
await ok('both-sided connect', bb.commit());
await no('add a third person to alice list', setDoc(conn(M, 'alice', 'bob2'), { name: 'X', blocked: false, since: ts() }));
await no('create pre-blocked/forged field', setDoc(conn(M, 'alice', 'mallory'), { name: 'M', blocked: false, since: ts(), extra: 1 }));
await no('read alice connections as bob', getDocs(collection(B, 'users', 'alice', 'connections')));
await ok('alice reads her connections', getDocs(collection(A, 'users', 'alice', 'connections')));
await no('bob renames himself in alice list', updateDoc(conn(B, 'alice', 'bob'), { name: 'Bobby' }));

console.log('gifts');
const gift = (db, to, from, name) => addDoc(collection(db, 'users', to, 'inbox'), { from, fromName: name, createdAt: ts(), seen: false });
await ok('bob gifts alice', gift(B, 'alice', 'bob', 'Bob'));
await ok('alice gifts bob', gift(A, 'bob', 'alice', 'Alice'));
await no('mallory (not connected) gifts alice', gift(M, 'alice', 'mallory', 'M'));
await no('bob forges sender', gift(B, 'alice', 'mallory', 'M'));
await no('gift to self', gift(A, 'alice', 'alice', 'A'));
await no('backdated gift', addDoc(collection(B, 'users', 'alice', 'inbox'), { from: 'bob', fromName: 'Bob', createdAt: new Date(0), seen: false }));
await ok('alice reads inbox (ordered query)', getDocs(query(collection(A, 'users', 'alice', 'inbox'), orderBy('createdAt', 'desc'), limit(20))));
await no('bob reads alice inbox', getDocs(collection(B, 'users', 'alice', 'inbox')));
let ids; await env.withSecurityRulesDisabled(async c => { ids = (await getDocs(collection(c.firestore(), 'users', 'alice', 'inbox'))).docs.map(d => d.id); });
await ok('alice marks seen', updateDoc(doc(A, 'users', 'alice', 'inbox', ids[0]), { seen: true }));
await no('alice edits sender', updateDoc(doc(A, 'users', 'alice', 'inbox', ids[0]), { from: 'x' }));

console.log('blocking');
await no('bob changes the block flag in alice list', updateDoc(conn(B, 'alice', 'bob'), { blocked: true }));
await ok('alice blocks bob', updateDoc(conn(A, 'alice', 'bob'), { blocked: true }));
await no('blocked bob gifts alice', gift(B, 'alice', 'bob', 'Bob'));
await no('blocked bob deletes his entry to escape', deleteDoc(conn(B, 'alice', 'bob')));
await no('blocked bob re-creates entry', setDoc(conn(B, 'alice', 'bob'), { name: 'Bob', blocked: false, since: ts() }));
await ok('alice unblocks bob', updateDoc(conn(A, 'alice', 'bob'), { blocked: false }));
await ok('bob gifts again', gift(B, 'alice', 'bob', 'Bob'));

console.log('account deletion (bob)');
await ok('bob removes himself from alice list', deleteDoc(conn(B, 'alice', 'bob')));
await ok('bob deletes own connection', deleteDoc(conn(B, 'bob', 'alice')));
let bobInbox; await env.withSecurityRulesDisabled(async c => { bobInbox = (await getDocs(collection(c.firestore(), 'users', 'bob', 'inbox'))).docs.map(d => d.id); });
for (const id of bobInbox) await ok('bob deletes received gift', deleteDoc(doc(B, 'users', 'bob', 'inbox', id)));
await no('mallory deletes bob code', deleteDoc(doc(M, 'codes', 'BBBBB2')));
await ok('bob deletes code', deleteDoc(doc(B, 'codes', 'BBBBB2')));
await ok('bob deletes profile', deleteDoc(doc(B, 'users', 'bob')));
await env.cleanup();
console.log(`\n${n - fail}/${n} checks passed`); process.exit(fail ? 1 : 0);
